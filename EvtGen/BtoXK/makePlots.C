    bool stats = false;

    TString lightNeutralStr = "#pi^{0}";
    double pDmax = 210;
    if (inFile.Contains("gamma") || inFile.Contains("GAMMA")) lightNeutralStr = "#gamma";
    //if (!inFile.Contains("gamma")) pDmax = 105;
