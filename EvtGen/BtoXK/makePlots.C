      p_pi0_D0D0B.Boost(boosttoD0D0B);

      TVector3 p_D0_D0D0B3 = p_D0_D0D0B.Vect();
      TVector3 p_pi0_D0D0B3 = p_pi0_D0D0B.Vect();
      Double_t numerator_D0D0B = p_D0_D0D0B3.Dot(p_pi0_D0D0B3);
      Double_t denominator_D0D0B = (p_D0_D0D0B3.Mag())*(p_pi0_D0D0B3.Mag());
      Double_t cosTheta_D0D0B = numerator_D0D0B/denominator_D0D0B; // Helicity Angle

      TLorentzVector p_D0_D0pi0(p_D0);
      TLorentzVector p_D0B_D0pi0(p_D0B);
      TLorentzVector p_pi0_D0pi0(p_pi0);

      p_pi0_D0pi0.Boost(boosttoD0pi0);
      p_D0B_D0pi0.Boost(boosttoD0pi0);

      TVector3 p_D0B_D0pi03 = p_D0B_D0pi0.Vect();
      TVector3 p_pi0_D0pi03 = p_pi0_D0pi0.Vect();
      Double_t numerator_D0pi0 = p_D0B_D0pi03.Dot(p_pi0_D0pi03);
      Double_t denominator_D0pi0 = (p_D0B_D0pi03.Mag())*(p_pi0_D0pi03.Mag());
      Double_t cosTheta_D0pi0 = numerator_D0pi0/denominator_D0pi0; // Helicity Angle

      TLorentzVector p_D0_D0Bpi0(p_D0);
      TLorentzVector p_D0B_D0Bpi0(p_D0B);
      TLorentzVector p_pi0_D0Bpi0(p_pi0);

      p_D0_D0Bpi0.Boost(boosttoD0Bpi0);
      p_D0B_D0Bpi0.Boost(boosttoD0Bpi0);

